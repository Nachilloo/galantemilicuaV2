/** Proyectos con página propia (excluye los que usaban `singlePage: '#'`). */
export const projectsWithPage: Project[] = projects.filter((p) => p.legacyHtml !== '#');

/** Búsqueda por slug (para la ruta dinámica). */
export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/** Mapa filename legacy -> slug (para redirects). */
export const legacyHtmlToSlug: Record<string, string> = Object.fromEntries(
  projects.filter((p) => p.legacyHtml !== '#').map((p) => [p.legacyHtml, p.slug]),
);

