export type ProjectMediaType = 'image' | 'video';

export interface ProjectSlide {
  image: string;
  zoomImage: string;
  /** Número visible en la esquina (".01", ".02", …). */
  slideNumber: string;
  title: string;
  description: string;
}

export interface Project {
  id: number;
  /** URL amigable dentro de /portfolio/. */
  slug: string;
  /** Nombre del archivo .html original (para redirects legacy). */
  legacyHtml: string;
  title: string;
  /** Imagen usada en el grid del portfolio. */
  gridImage: string;
  /** Miniatura pequeña (thumb). */
  thumbnail: string;
  categories: string[];
  categoryLabels: string[];
  hasSpecialClass: boolean;
  specialClass?: string;
  hasHiddenAnim: boolean;
  mediaType: ProjectMediaType;
  videoUrl?: string;
  /** True si el proyecto NO aparece en el grid pero sí tiene página propia. */
  unlisted: boolean;
  slides: ProjectSlide[];
  /** Slug del siguiente proyecto para el botón "Next Project". */
  nextSlug?: string;
  /** Etiqueta usada bajo el botón "Next" (ej. "Project Title"). */
  nextLabel?: string;
}

